import uuid
from datetime import datetime

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    String,
    Text,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.db import Base
from app.models._mixins import created_at, updated_at, uuid_pk


class Position(Base):
    __tablename__ = "positions"

    # Declared here as well as in migration a3f7c1d20e94 so the two ways this
    # schema gets built agree: Alembic in dev/prod, Base.metadata.create_all in
    # the test suite. Without this the CHECK would be absent under pytest and
    # an invalid sensitivity would pass tests but fail on real Postgres.
    __table_args__ = (
        CheckConstraint(
            "status IN ('open', 'paused', 'closed')",
            name="ck_positions_status",
        ),
        CheckConstraint(
            "sensitivity IN ('public', 'nda', 'restricted')",
            name="ck_positions_sensitivity",
        ),
        Index(
            "ix_positions_sensitivity_confidential",
            "sensitivity",
            postgresql_where=text("sensitivity <> 'public'"),
        ),
    )

    id: Mapped[uuid.UUID] = uuid_pk()
    organization_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("organizations.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    title: Mapped[str] = mapped_column(String(255), nullable=False)
    # Short, recruiter-facing summary — 1-3 sentences. Shown on cards and as
    # the lead paragraph on the detail page. NEVER includes office addresses,
    # contact info, or "we are looking for…" boilerplate.
    description: Mapped[str | None] = mapped_column(Text, nullable=True)
    # Optional verbose description: original ad text or extended job spec.
    # Lives behind a "Подробнее" disclosure on the detail page; never shown
    # on cards. Always derived from the source — we never invent content here.
    full_description: Mapped[str | None] = mapped_column(Text, nullable=True)
    requirements: Mapped[dict | None] = mapped_column(JSONB, nullable=True)
    internal_notes: Mapped[str | None] = mapped_column(Text, nullable=True)
    status: Mapped[str] = mapped_column(String(16), nullable=False, default="open")

    # How much of this role may be shown to an unauthenticated visitor.
    # 'public'     — everything (the historical behaviour, and the default).
    # 'nda'        — commercial confidentiality: employer identity, the raw ad
    #                text and internal-system detail are withheld.
    # 'restricted' — гос. важность: the above plus salary and the tech stack,
    #                so the vacancy cannot be used to fingerprint infrastructure.
    # Enforced by a CHECK constraint; the redaction rules themselves live in
    # app/services/public_positions.py so every public surface shares one policy.
    sensitivity: Mapped[str] = mapped_column(
        String(16), nullable=False, server_default="public", default="public"
    )

    # Recruiter-facing prose portrait of the person we are looking for, derived
    # from `requirements` by the LLM and then hand-editable. INTERNAL ONLY —
    # it is written against internal context and must never appear in a public
    # schema (note /openapi.json is unauthenticated).
    candidate_profile: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Sanitised stand-in for `description`, shown to the public instead of the
    # real one when sensitivity != 'public'. Generated by the LLM, editable.
    # NULL means "no vetted public text exists yet" — the public surfaces then
    # show nothing rather than falling back to the unredacted description.
    public_description: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Optional grouping label, e.g. "telecom" or "demo". Free text on
    # purpose — the UI groups by distinct values rather than referencing a
    # separate folders table. Indexed for fast filtering.
    folder: Mapped[str | None] = mapped_column(
        String(64), nullable=True, index=True
    )

    # Canonical link to the folders tree. NULL = Unsorted. The legacy `folder`
    # string above is KEPT as a denormalized, write-synced shadow: import
    # scripts and string-based readers keep working. folder_id is the source of
    # truth when set; the API writes folder = <folder.name> on every folder_id
    # assignment so the two never diverge. ON DELETE SET NULL: deleting a folder
    # orphans its positions to Unsorted, never deletes the role.
    folder_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("folders.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )

    # When true, the position has a public /apply/{id} page that anyone with
    # the link can submit a CV through. Default true for new positions; the
    # recruiter can disable per-position via PATCH.
    public_apply_enabled: Mapped[bool] = mapped_column(
        Boolean, nullable=False, server_default="true", default=True
    )

    created_by: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL"), nullable=True
    )
    deleted_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True, index=True
    )
    deleted_by_user_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
    )
    created_at: Mapped[datetime] = created_at()
    updated_at: Mapped[datetime] = updated_at()
