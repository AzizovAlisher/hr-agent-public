function titleCase(value: string): string {
  return value ? value[0].toLocaleUpperCase() + value.slice(1) : value;
}

export function machineLabel(value: string, locale: ProductLocale): string {
  const exact = EXACT[locale][value];
  if (exact) return exact;

  const tokens = value.split(/[.:/_-]+/).filter(Boolean);
  if (!tokens.length) return value;
  const words = tokens.map((token) => {
    if (locale === "ru") return TOKEN_RU[token.toLowerCase()] ?? token;
    const upper = token.toUpperCase();
    if (["AI", "API", "CSV", "HTTP", "HTTPS", "ID", "LLM", "MFA", "OAUTH", "PII", "SSO", "URL", "XLSX"].includes(upper)) {
      return upper === "OAUTH" ? "OAuth" : upper;
    }
    return token.toLowerCase();
  });
  return titleCase(words.join(" "));
}
